#!/usr/bin/env node
/**
 * Builds a fully self-contained copy of the design preview:
 *
 *   docs/preview/index.html            → docs/preview/gallirent-preview.html
 *
 * Photos are embedded once each as base64 data URIs and assigned to every
 * <img data-img="…"> placeholder by a small inline script. The result renders
 * with no server and no sibling asset folder (file viewers, email, USB copy).
 *
 * Run: node scripts/build-preview.mjs   (or: npm run preview:bundle)
 */
import { readFile, writeFile } from 'node:fs/promises';
import { extname, join, resolve } from 'node:path';

const ROOT = resolve(process.cwd(), 'docs/preview');
const SOURCE = join(ROOT, 'index.html');
const TARGET = join(ROOT, 'gallirent-preview.html');

const MIME = { '.jpg': 'image/jpeg', '.jpeg': 'image/jpeg', '.png': 'image/png', '.webp': 'image/webp' };
// 1×1 transparent GIF used only until the inline script assigns the real source.
const PLACEHOLDER = 'data:image/gif;base64,R0lGODlhAQABAIAAAAAAAP///yH5BAEAAAAALAAAAAABAAEAAAIBRAA7';

const html = await readFile(SOURCE, 'utf8');
const refs = [...new Set([...html.matchAll(/src="(images\/[^"]+)"/g)].map((match) => match[1]))];

if (refs.length === 0) {
  console.error('No image references found — is docs/preview/index.html intact?');
  process.exit(1);
}

/** @type {Record<string,string>} */
const embedded = {};
let sourceBytes = 0;
let output = html;

for (const ref of refs) {
  const file = join(ROOT, ref);
  const buffer = await readFile(file);
  sourceBytes += buffer.byteLength;
  const mime = MIME[extname(file).toLowerCase()] || 'application/octet-stream';
  const key = ref.replace(/^images\//, '').replace(/\.[^.]+$/, '');
  embedded[key] = `data:${mime};base64,${buffer.toString('base64')}`;
  output = output.split(`src="${ref}"`).join(`src="${PLACEHOLDER}" data-img="${key}"`);
}

const assigner = [
  '<script>',
  '  // Single-file build: each photo is embedded once and shared by every placement.',
  `  var __GALLIRENT_IMAGES__ = ${JSON.stringify(embedded)};`,
  '  document.querySelectorAll("img[data-img]").forEach(function (img) {',
  '    var key = img.getAttribute("data-img");',
  '    if (__GALLIRENT_IMAGES__[key]) img.src = __GALLIRENT_IMAGES__[key];',
  '  });',
  '</script>',
].join('\n');

output = output.replace('</body>', `${assigner}\n</body>`);
output = output.replace(
  '<title>GalliRent — UI preview (native Android)</title>',
  '<title>GalliRent — UI preview (single file)</title>',
);
output = output.replace(
  '<html lang="en">',
  '<html lang="en">\n<!-- Generated by scripts/build-preview.mjs from index.html. Do not edit directly. -->',
);

await writeFile(TARGET, output);

const remainingRelative = [...output.matchAll(/src="images\//g)].length;
const placeholders = [...output.matchAll(/data-img="/g)].length;

console.log(`Embedded ${refs.length} photos (${(sourceBytes / 1024).toFixed(0)} KB source) → ${TARGET}`);
console.log(`Output ${(output.length / 1024).toFixed(0)} KB · image placeholders: ${placeholders} · relative refs left: ${remainingRelative}`);
if (remainingRelative > 0) process.exit(1);
